// Prebuilt LUT lane for webgl_postprocessing_3dlut ("3d luts долго грузит").
//
// The official module eagerly loads ALL nine LUTs at boot. On the R1 runtime
// that meant: (a) the 13MB fully-inlined widget.js (base64 CUBE/3dl text +
// PNG strips + helmet + HDR) evaluated and registered in QuickJS before the
// first frame, and (b) five 885KB .CUBE files plus one 450KB .3dl parsed
// with a per-line regex walk (~262k regexp exec calls per file) on the main
// QuickJS thread — multi-second frame stalls. LUTImageLoader additionally
// needs a canvas2d getImageData round trip per strip.
//
// prepare.mjs now externalizes every asset for this widget (per-example
// inlineMaxBytes) and pins nine 'J3LT' prebuilt bins (generated by
// generate_lut_bins.mjs, byte-parity verified against the official parse)
// under the ORIGINAL asset urls. This module overrides the three loaders:
// each fetch()es the bin through the runtime host asset lane and rebuilds
// the Data3DTexture from a zero-copy Uint8Array view — the loaders' exact
// UnsignedByteType/RGBAFormat/LinearFilter/ClampToEdge output shape.
import {
  ClampToEdgeWrapping, Data3DTexture, LinearFilter, Loader, RGBAFormat,
  UnsignedByteType, Vector3
} from 'three';

const MAGIC_J3LT = 0x544c334a; // 'J3LT' little-endian

function parseBin(buffer, withDomain) {
  const view = new DataView(buffer);
  if (buffer.byteLength < 36 || view.getUint32(0, true) !== MAGIC_J3LT) {
    throw new Error('three: prebuilt LUT header mismatch (expected J3LT v1)');
  }
  const version = view.getUint32(4, true);
  if (version !== 1) throw new Error(`three: unsupported prebuilt LUT version ${version}`);
  const size = view.getUint32(8, true);
  const expected = 36 + size ** 3 * 4;
  if (buffer.byteLength !== expected) {
    throw new Error(`three: prebuilt LUT payload mismatch (${buffer.byteLength} != ${expected})`);
  }
  const texture3D = new Data3DTexture();
  texture3D.image.data = new Uint8Array(buffer, 36); // zero-copy view
  texture3D.image.width = size;
  texture3D.image.height = size;
  texture3D.image.depth = size;
  texture3D.format = RGBAFormat;
  texture3D.type = UnsignedByteType;
  texture3D.magFilter = LinearFilter;
  texture3D.minFilter = LinearFilter;
  texture3D.wrapS = ClampToEdgeWrapping;
  texture3D.wrapT = ClampToEdgeWrapping;
  texture3D.wrapR = ClampToEdgeWrapping;
  texture3D.generateMipmaps = false;
  texture3D.needsUpdate = true;
  if (!withDomain) return { size, texture3D };
  return {
    size,
    domainMin: new Vector3(
      view.getFloat32(12, true), view.getFloat32(16, true), view.getFloat32(20, true)),
    domainMax: new Vector3(
      view.getFloat32(24, true), view.getFloat32(28, true), view.getFloat32(32, true)),
    texture3D
  };
}

function fetchBin(url) {
  console.time('jsr.lut.prebuilt');
  return fetch(url).then(response => {
    if (response.status !== 200 && response.status !== 0) {
      throw new Error(`three: prebuilt LUT fetch failed (${response.status}) for ${url}`);
    }
    return response.arrayBuffer();
  }).then(buffer => {
    console.timeEnd('jsr.lut.prebuilt');
    return buffer;
  });
}

export class LUTCubeLoader extends Loader {

  load(url, onLoad, onProgress, onError) {
    fetchBin(url).then(buffer => {
      const title = null;
      try {
        const result = parseBin(buffer, true);
        result.title = title;
        onLoad(result);
      } catch (e) {
        if (onError) onError(e);
        else console.error(e);
        if (this.manager && this.manager.itemError) this.manager.itemError(url);
      }
    }, error => {
      if (onError) onError(error);
      else console.error(error);
      if (this.manager && this.manager.itemError) this.manager.itemError(url);
    });
  }

}


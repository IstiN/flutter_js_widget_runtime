// Regenerate the indexed Stanford Bunny used by the bounded FBXLoader shim.
// Usage: node tool/three_example/generate_fbx_bunny_geometry.mjs /tmp/jsr-three-r186
// The input FBX is the already pinned example asset; no network access is used.
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const source = process.argv[2];
if (!source) throw new Error('usage: generate_fbx_bunny_geometry.mjs <three-r186-source>');
const { FBXLoader } = await import(pathToFileURL(path.join(source, 'examples/jsm/loaders/FBXLoader.js')));
const { mergeVertices } = await import(pathToFileURL(path.join(source, 'examples/jsm/utils/BufferGeometryUtils.js')));
const input = 'example/widgets/three-raycaster-bvh/models__fbx__stanford-bunny.fbx';
const output = 'tool/three_example/degrades/fbx_bunny_geometry.mjs';
const bytes = await readFile(input);
const group = new FBXLoader().parse(bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength), '');
let sourceMesh = null;
group.traverse(object => { if (object.isMesh && !sourceMesh) sourceMesh = object; });
if (!sourceMesh) throw new Error('Stanford Bunny mesh not found');
const geometry = mergeVertices(sourceMesh.geometry, 1e-4);
const positions = geometry.attributes.position;
const normals = geometry.attributes.normal;
if (!normals || !geometry.index) throw new Error('indexed normals are required');

function literal(array, digits) {
  const values = Array.from(array, value => Number(value.toFixed(digits)));
  const rows = [];
  for (let index = 0; index < values.length; index += 256) rows.push(values.slice(index, index + 256).join(','));
  return rows.join(',\n');
}
const text = `// GENERATED by tool/three_example/generate_fbx_bunny_geometry.mjs.\n` +
  `// Source: the pinned Stanford Bunny FBX; indexed offline, not parsed by QuickJS.\n` +
  `export const bunnyPositions = new Float32Array([\n${literal(positions.array, 6)}\n]);\n` +
  `export const bunnyNormals = new Float32Array([\n${literal(normals.array, 6)}\n]);\n` +
  `export const bunnyIndices = new Uint32Array([\n${literal(geometry.index.array, 0)}\n]);\n`;
await writeFile(output, text);
console.log(`${output}: ${positions.count} vertices, ${geometry.index.count / 3} triangles`);

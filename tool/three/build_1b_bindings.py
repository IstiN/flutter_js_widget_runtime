#!/usr/bin/env python3
"""build_1b_bindings.py — G1 bindings generator (M2a).

Reads tool/three/webgl2_g1_methods.json (source of truth) and emits:
  native/angle/gen/g1_tables.h  — opcode enum + dispatch switch (the switch
                                  body is guarded by A1B_DISPATCH_IMPL and is
                                  included once from angle_1b_dispatch.c).
  tool/three/gen/g1_packer.js   — G1 byte writer, g1.<method> packers and
                                  G1C.<METHOD_NAME> opcode constants.

python3 stdlib only. Deterministic: output depends only on the JSON.
Usage: python3 tool/three/build_1b_bindings.py
"""
import json
import re
import sys
from collections import OrderedDict
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent.parent
JSON_PATH = REPO / "tool/three/webgl2_g1_methods.json"
GL_H_PATH = REPO / "native/angle/angle_1b_gl.h"
OUT_TABLES = REPO / "native/angle/gen/g1_tables.h"
OUT_PACKER = REPO / "tool/three/gen/g1_packer.js"

ARG_CHARS = set("uifsb")
RETS = {"void", "i32", "u32", "name", "scratch"}


def snake(name):
    s = re.sub(r"(?<!^)(?=[A-Z])", "_", name)
    s = re.sub(r"_(\d+)_([A-Z])", r"_\1\2", s)  # Image2_D -> Image2D
    return s.upper()


def load_methods():
    with open(JSON_PATH, encoding="utf-8") as f:
        data = json.load(f, object_pairs_hook=OrderedDict)
    methods = data["methods"]
    seen = set()
    for i, m in enumerate(methods, 1):
        if m["name"] in seen:
            raise SystemExit(f"duplicate method name: {m['name']}")
        seen.add(m["name"])
        if m["opcode"] != i:
            raise SystemExit(f"{m['name']}: opcode {m['opcode']} != sequential {i}")
        bad = set(m.get("args", "")) - ARG_CHARS
        if bad:
            raise SystemExit(f"{m['name']}: bad arg chars {bad}")
        if m.get("ret") not in RETS:
            raise SystemExit(f"{m['name']}: bad ret {m.get('ret')}")
        if "stub" not in m and not m.get("c"):
            raise SystemExit(f"{m['name']}: non-stub without C glue")
    return methods


def gl_ptr_names(methods):
    """g_* identifiers referenced by the C glue — must exist in the X-tables."""
    refs = set()
    for m in methods:
        refs.update(re.findall(r"\bg_[A-Za-z0-9]+\b", m.get("c", "")))
    return refs


def check_xtables(refs):
    src = GL_H_PATH.read_text(encoding="utf-8")
    # X-list entries look like:  X(rett, Name, glName, (args))
    have = {"g_" + n for n in re.findall(r"X\([^,]+,\s*([A-Za-z0-9]+)\s*,", src)}
    missing = sorted(refs - have)
    if missing:
        raise SystemExit("angle_1b_gl.h X-lists are missing:\n  " + "\n  ".join(missing))


def emit_tables_h(methods):
    out = []
    out.append("// g1_tables.h — GENERATED by tool/three/build_1b_bindings.py from")
    out.append("// tool/three/webgl2_g1_methods.json. Do not edit; re-run the generator.")
    out.append("//")
    out.append("// Outside the impl guard: the G1_OP_* opcode enum (safe to include from")
    out.append("// any TU, e.g. the C packer in angle_1b.c). Inside A1B_DISPATCH_IMPL:")
    out.append("// the full dispatch switch, included once from angle_1b_dispatch.c in")
    out.append("// the middle of a1b_gl_dispatch(). Case bodies are self-contained: they")
    out.append("// declare rv/sc/sc_len, decode args into a0..aN via the g1_rd_* helpers,")
    out.append("// run the JSON 'c' glue, publish sc_len and return rv.")
    out.append("#ifndef A1B_G1_TABLES_H")
    out.append("#define A1B_G1_TABLES_H")
    out.append("")
    out.append("enum {")
    for m in methods:
        out.append(f"  G1_OP_{snake(m['name'])} = {m['opcode']},")
    out.append("};")
    out.append(f"#define G1_OP_COUNT {len(methods)}")
    out.append("")
    out.append("#ifdef A1B_DISPATCH_IMPL")
    out.append("")
    out.append("// Scratch append helper used by JSON glue (bounds-checked).")
    out.append("#define g1_sc_write(ptr, n) \\")
    out.append("  g1_scratch_write(sc, &sc_len, sc_cap, (const void *)(ptr), (size_t)(n))")
    out.append("")
    out.append("// Generated opcode switch. Included once from angle_1b_dispatch.c after")
    out.append("// the wire readers, scratch, sync table and glue helpers are defined.")
    out.append("static int64_t g1_dispatch_op(uint32_t opcode, g1_cur c) {")
    out.append("  switch (opcode) {")
    for m in methods:
        if "stub" in m:
            out.append(f"  case G1_OP_{snake(m['name'])}:")
            out.append(f"    return -1; // stub: {m['stub']} ({m.get('doc', '').rstrip('.')})")
            continue
        out.append(f"  case G1_OP_{snake(m['name'])}: {{")
        out.append("    uint8_t *const sc = g1_scratch;")
        out.append("    const size_t sc_cap = G1_SCRATCH_CAP;")
        out.append("    int sc_len = 0;")
        out.append("    int64_t rv = 0;")
        for idx, ch in enumerate(m["args"]):
            if ch == "u":
                out.append(f"    const uint32_t a{idx} = g1_rd_u32(&c);")
            elif ch == "i":
                out.append(f"    const int32_t a{idx} = (int32_t)g1_rd_u32(&c);")
            elif ch == "f":
                out.append(f"    const float a{idx} = g1_rd_f32(&c);")
            elif ch == "s":
                out.append(f"    const uint32_t a{idx}_len = g1_rd_u32(&c);")
                out.append(f"    const char *const a{idx} = g1_rd_str(&c, a{idx}_len);")
            elif ch == "b":
                out.append(f"    const uint32_t a{idx}_len = g1_rd_u32(&c);")
                out.append(f"    const void *const a{idx} = g1_rd_blob(&c, a{idx}_len);")
        out.append("    if (c.err) return G1_E_MALFORMED;")
        for line in m["c"].splitlines():
            out.append("    " + line.rstrip())
        out.append("    (void)sc;")
        out.append("    (void)sc_cap;")
        out.append("    if (sc_len) g1_scratch_len = sc_len; // helper-based glue already published")
        out.append("    return rv;")
        out.append("  }")
    out.append("  default:")
    out.append("    return -(int64_t)opcode; // unknown opcode")
    out.append("  }")
    out.append("}")
    out.append("#undef g1_sc_write")
    out.append("#endif // A1B_DISPATCH_IMPL")
    out.append("")
    out.append("#endif // A1B_G1_TABLES_H")
    out.append("")
    return "\n".join(out)


PACKER_PREAMBLE = """// g1_packer.js — GENERATED by tool/three/build_1b_bindings.py from
// tool/three/webgl2_g1_methods.json. Do not edit; re-run the generator.
//
// G1 byte writer + per-method packers. Wire format (locked ABI):
//   [u32 opcode LE][args...]  u=u32 i=i32 f=f32 s=u32 len+UTF-8 b=u32 len+bytes
// A 'b' arg given a number (or null) writes the length ONLY — the C decoder
// sees a NULL pointer (bufferData size-only / texImage2D null-data overloads).
// G1.call(opcode) invokes global __jsr1b_gl(bytes) synchronously, returns its
// int64 result and resets the buffer.
'use strict';
var G1C = {
"""

PACKER_CORE = """};

var G1 = (function () {
  var root = typeof globalThis !== 'undefined' ? globalThis : this;
  var _b = new Uint8Array(4096);
  var _l = 0;
  var _dv = new DataView(_b.buffer);
  function _grow(n) {
    if (_l + n <= _b.length) return;
    var cap = _b.length * 2;
    while (cap < _l + n) cap *= 2;
    var nb = new Uint8Array(cap);
    nb.set(_b.subarray(0, _l));
    _b = nb;
    _dv = new DataView(_b.buffer);
  }
  function u32(v) { _grow(4); _dv.setUint32(_l, Number(v) >>> 0, true); _l += 4; }
  function i32(v) { _grow(4); _dv.setInt32(_l, Number(v) | 0, true); _l += 4; }
  function f32(v) { _grow(4); _dv.setFloat32(_l, Number(v), true); _l += 4; }
  function _utf8(s) {
    var out = [], i = 0, c;
    for (; i < s.length; i++) {
      c = s.charCodeAt(i);
      if (c < 0x80) out.push(c);
      else if (c < 0x800) out.push(0xC0 | (c >> 6), 0x80 | (c & 63));
      else if (c >= 0xD800 && c <= 0xDBFF && i + 1 < s.length) {
        c = 0x10000 + ((c & 1023) << 10) | (s.charCodeAt(++i) & 1023);
        out.push(0xF0 | (c >> 18), 0x80 | ((c >> 12) & 63), 0x80 | ((c >> 6) & 63), 0x80 | (c & 63));
      } else out.push(0xE0 | (c >> 12), 0x80 | ((c >> 6) & 63), 0x80 | (c & 63));
    }
    return out;
  }
  function str(s) {
    var a = _utf8(String(s));
    u32(a.length);
    _grow(a.length);
    _b.set(a, _l);
    _l += a.length;
  }
  function blob(v) {
    var a, i;
    if (v == null) { u32(0); return; }
    if (typeof v === 'number') { u32(v); return; } // size-only / null-data convention
    if (Array.isArray(v)) { // plain GLenum[] (drawBuffers/invalidateFramebuffer):
      u32(v.length * 4);   // blob len in BYTES; decoder divides by 4
      _grow(v.length * 4);
      for (i = 0; i < v.length; i++) _dv.setUint32(_l + i * 4, Number(v[i]) >>> 0, true);
      _l += v.length * 4;
      return;
    }
    if (v instanceof Uint8Array) a = v;
    else a = new Uint8Array(v.buffer, v.byteOffset || 0, v.byteLength);
    u32(a.byteLength);
    _grow(a.byteLength);
    for (i = 0; i < a.byteLength; i++) _b[_l + i] = a[i];
    _l += a.byteLength;
  }
  function call(op) {
    var bytes = _b.subarray(0, _l);
    var rc = root.__jsr1b_gl(bytes); // sync host call; the view is valid for the call only
    _l = 0;
    return rc;
  }
  return { u32: u32, i32: i32, f32: f32, str: str, blob: blob, call: call };
})();

var g1 = {
"""


def emit_packer_js(methods):
    out = [PACKER_PREAMBLE]
    consts = [f"  {snake(m['name'])}: {m['opcode']}" for m in methods]
    out.append(",\n".join(consts))
    out.append(PACKER_CORE)
    writers = {"u": "G1.u32", "i": "G1.i32", "f": "G1.f32", "s": "G1.str", "b": "G1.blob"}
    for m in methods:
        name = m["name"]
        if "stub" in m:
            out.append(f"  {name}: function () {{")
            out.append(f"    throw new Error('{m['stub']}: named unsupported (G1 stub)');")
            out.append("  },")
            continue
        params = ", ".join(f"x{i}" for i in range(len(m["args"])))
        out.append(f"  {name}: function ({params}) {{")
        out.append(f"    G1.u32(G1C.{snake(name)});")
        for i, ch in enumerate(m["args"]):
            out.append(f"    {writers[ch]}(x{i});")
        out.append(f"    return G1.call(G1C.{snake(name)});")
        out.append("  },")
    out.append("};")
    out.append("")
    out.append("if (typeof module !== 'undefined' && module.exports) {")
    out.append("  module.exports = { G1: G1, g1: g1, G1C: G1C };")
    out.append("}")
    out.append("")
    return "\n".join(out)


def main():
    methods = load_methods()
    check_xtables(gl_ptr_names(methods))
    OUT_TABLES.parent.mkdir(parents=True, exist_ok=True)
    OUT_PACKER.parent.mkdir(parents=True, exist_ok=True)
    OUT_TABLES.write_text(emit_tables_h(methods), encoding="utf-8")
    OUT_PACKER.write_text(emit_packer_js(methods), encoding="utf-8")
    by_cat = OrderedDict()
    for m in methods:
        by_cat.setdefault(m["cat"], 0)
        by_cat[m["cat"]] += 1
    print(f"g1_tables.h : {OUT_TABLES.relative_to(REPO)} ({len(methods)} methods)")
    print(f"g1_packer.js: {OUT_PACKER.relative_to(REPO)}")
    for cat, n in by_cat.items():
        print(f"  {cat:8s} {n}")


if __name__ == "__main__":
    main()
